import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vitest/config';

const MINIMUM_COVERAGE_PERCENT = 80;

// gluestack renders through react-native-web, as the Next.js build does with
// @gluestack/ui-next-adapter: alias react-native and prefer `.web` files.
// NativeWind's runtime only compiles inside an app bundler, so tests get a
// stand-in (see src/testing/nativewindStub.ts).
const reactNativeWebResolve = {
  alias: [
    { find: /^react-native$/, replacement: 'react-native-web' },
    {
      find: /^nativewind$/,
      replacement: fileURLToPath(
        new URL('./src/testing/nativewindStub.ts', import.meta.url),
      ),
    },
  ],
  extensions: [
    '.web.tsx',
    '.web.ts',
    '.web.jsx',
    '.web.js',
    '.tsx',
    '.ts',
    '.jsx',
    '.js',
    '.mjs',
    '.json',
  ],
};

export default defineConfig({
  // tsconfig.json sets `jsxImportSource: nativewind` for the app; tests use
  // React's own runtime because nativewind is stubbed here (see the alias above).
  plugins: [react({ jsxImportSource: 'react' })],
  // Resolves the `@/*` alias declared in tsconfig.json.
  resolve: { tsconfigPaths: true },
  test: {
    globals: true,
    projects: [
      {
        extends: true,
        resolve: reactNativeWebResolve,
        test: {
          name: 'unit',
          environment: 'jsdom',
          setupFiles: ['./vitest.setup.ts'],
          include: ['src/**/*.spec.{ts,tsx}'],
        },
      },
      {
        extends: true,
        test: {
          // The CI scripts' specs spawn Bash and Git, so they need Node, not jsdom.
          name: 'scripts',
          environment: 'node',
          include: ['.github/scripts/**/*.spec.ts'],
        },
      },
    ],
    coverage: {
      provider: 'v8',
      // Without `include`, Vitest only measures files the tests import, so an
      // untested file would never lower the percentage.
      include: ['src/**/*.{ts,tsx}'],
      exclude: [
        // Root layouts render <html>/<body>, which jsdom can't mount inside a container.
        'src/**/layout.tsx',
        // Flushes react-native-web styles during server rendering, which only a real
        // Next.js request exercises (covered by `yarn test:e2e`).
        'src/app/registry.tsx',
        // gluestack-ui components are generated by its CLI (vendored), not written here.
        'src/components/ui/**',
        'src/**/*.spec.{ts,tsx}',
        // Browser-only code, covered by Playwright (`yarn test:e2e`) instead.
        'src/**/*.e2e.ts',
        'src/testing/**',
      ],
      reporter: ['text', 'html', 'lcov'],
      reportOnFailure: true,
      thresholds: {
        lines: MINIMUM_COVERAGE_PERCENT,
        branches: MINIMUM_COVERAGE_PERCENT,
        functions: MINIMUM_COVERAGE_PERCENT,
        statements: MINIMUM_COVERAGE_PERCENT,
      },
    },
  },
});
